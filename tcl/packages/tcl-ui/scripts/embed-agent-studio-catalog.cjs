/**
 * Embed agent-core template JSON for Netlify proxy fallback.
 * When Railway tcl-core is stale, GET /api/agent-studio/templates/* still returns data.
 *
 * Regenerate: node scripts/embed-agent-studio-catalog.cjs
 */
const fs = require('fs');
const path = require('path');

const uiRoot = path.join(__dirname, '..');
const agentTemplates = path.join(uiRoot, '..', 'agent-core', 'templates');
const outFile = path.join(uiRoot, 'netlify', 'functions', 'agent-studio-catalog.js');

function readJson(name) {
  const p = path.join(agentTemplates, name);
  if (!fs.existsSync(p)) {
    throw new Error(`[embed-agent-studio-catalog] missing ${p}`);
  }
  return JSON.parse(fs.readFileSync(p, 'utf8'));
}

const roles = readJson('roles.json');
const personas = readJson('personas.json');
const workflows = readJson('workflows.json');

const body = `/**
 * AUTO-GENERATED by scripts/embed-agent-studio-catalog.cjs — do not edit by hand.
 * Source: packages/agent-core/templates/*.json
 */
'use strict';

module.exports = {
  roles: ${JSON.stringify(roles)},
  personas: ${JSON.stringify(personas)},
  workflows: ${JSON.stringify(workflows)},
};
`;

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, body, 'utf8');
console.log(
  '[embed-agent-studio-catalog] wrote',
  outFile,
  `(${roles.length} roles, ${personas.length} personas, ${workflows.length} workflows)`
);
