'use strict';

/**
 * Writes src/assets/supabase-env.js before `ng build` / `ng serve`.
 * Values (in order): process.env → optional packages/tcl-ui/.env.supabase (KEY=VAL lines).
 *
 * Netlify: set SUPABASE_URL and SUPABASE_ANON_KEY (anon key only).
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const outDir = path.join(root, 'src', 'assets');
const outFile = path.join(outDir, 'supabase-env.js');

function readDotEnv(filePath) {
  const out = {};
  if (!fs.existsSync(filePath)) return out;
  const text = fs.readFileSync(filePath, 'utf8');
  for (const line of text.split(/\r?\n/)) {
    const t = line.trim();
    if (!t || t.startsWith('#')) continue;
    const eq = t.indexOf('=');
    if (eq <= 0) continue;
    const k = t.slice(0, eq).trim();
    let v = t.slice(eq + 1).trim();
    if ((v.startsWith('"') && v.endsWith('"')) || (v.startsWith("'") && v.endsWith("'"))) {
      v = v.slice(1, -1);
    }
    out[k] = v;
  }
  return out;
}

const dot = readDotEnv(path.join(root, '.env.supabase'));

const url = (
  process.env.SUPABASE_URL ||
  process.env.NEXT_PUBLIC_SUPABASE_URL ||
  process.env.VITE_SUPABASE_URL ||
  process.env.PUBLIC_SUPABASE_URL ||
  dot.SUPABASE_URL ||
  ''
).trim();

const anonKey = (
  process.env.SUPABASE_ANON_KEY ||
  process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY ||
  process.env.VITE_SUPABASE_ANON_KEY ||
  process.env.PUBLIC_SUPABASE_ANON_KEY ||
  dot.SUPABASE_ANON_KEY ||
  ''
).trim();

fs.mkdirSync(outDir, { recursive: true });

const body = `/* Generated by scripts/inject-supabase-assets.cjs — do not edit */
window.__SUPABASE_URL = ${JSON.stringify(url)};
window.__SUPABASE_ANON_KEY = ${JSON.stringify(anonKey)};
`;

fs.writeFileSync(outFile, body, 'utf8');

if (url && anonKey) {
  console.log('[inject-supabase-assets] Wrote', path.relative(root, outFile), '(Supabase URL + anon key present)');
} else {
  console.warn(
    '[inject-supabase-assets] Wrote empty Supabase config. Set SUPABASE_URL + SUPABASE_ANON_KEY (Netlify env) or create packages/tcl-ui/.env.supabase — see README.'
  );
}
