/**
 * Embed generic agent markdown assets for production seeding (no filesystem dependency).
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const here = path.dirname(fileURLToPath(import.meta.url));
const tclCoreRoot = path.join(here, '..');
const genericDir = path.join(tclCoreRoot, '..', 'agent-core', 'templates', 'assets', 'generic');
const outFile = path.join(tclCoreRoot, 'src', 'server', 'agent-studio', 'generated-agent-generic-files.ts');

const FILES = [
  'agent.md',
  'persona.md',
  'instructions.md',
  'rules.md',
  'tools.md',
  'memory.md',
  'context.md',
  'workflow.md',
  'review-gates.md',
  'handoff.md',
  'heartbeat.md',
  'output-format.md',
];

const missing = FILES.filter((f) => !fs.existsSync(path.join(genericDir, f)));
if (missing.length > 0) {
  if (fs.existsSync(outFile) && fs.statSync(outFile).size > 500) {
    console.log(
      '[embed-generic-agent-files] skip: missing',
      missing.join(', '),
      '; keeping committed',
      outFile
    );
    process.exit(0);
  }
  console.error('[embed-generic-agent-files] FATAL: missing assets and no committed file');
  process.exit(1);
}

const map = {};
for (const f of FILES) {
  map[f] = fs.readFileSync(path.join(genericDir, f), 'utf8');
}

const banner = `/**
 * AUTO-GENERATED by scripts/embed-generic-agent-files.mjs — do not edit by hand.
 * Source: packages/agent-core/templates/assets/generic/*.md
 */\n`;

const body =
  banner +
  `export const BUILTIN_GENERIC_AGENT_FILES: Record<string, string> = ${JSON.stringify(map)};\n`;

fs.writeFileSync(outFile, body, 'utf8');
console.log('[embed-generic-agent-files] wrote', outFile, `(${FILES.length} files)`);
