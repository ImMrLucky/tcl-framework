/**
 * Emit `generated-agent-catalog.ts` from `agent-core` JSON so production APIs
 * never depend on disk layout (Docker, Netlify, missing agent-template-json).
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const here = path.dirname(fileURLToPath(import.meta.url));
const tclCoreRoot = path.join(here, '..');
const agentTemplates = path.join(tclCoreRoot, '..', 'agent-core', 'templates');
const outFile = path.join(tclCoreRoot, 'src', 'server', 'agent-studio', 'generated-agent-catalog.ts');

const files = ['roles.json', 'personas.json', 'workflows.json'];
for (const f of files) {
  const p = path.join(agentTemplates, f);
  if (!fs.existsSync(p)) {
    console.error('[embed-agent-catalog] missing:', p);
    process.exit(1);
  }
}

const roles = JSON.parse(fs.readFileSync(path.join(agentTemplates, 'roles.json'), 'utf8'));
const personas = JSON.parse(fs.readFileSync(path.join(agentTemplates, 'personas.json'), 'utf8'));
const workflows = JSON.parse(fs.readFileSync(path.join(agentTemplates, 'workflows.json'), 'utf8'));

const banner = `/**
 * AUTO-GENERATED by scripts/embed-agent-catalog.mjs — do not edit by hand.
 * Source: packages/agent-core/templates/*.json
 * Regenerate: run "npm run prebuild" in packages/tcl-core (runs before npm run build).
 */
`;

const body = `${banner}
export const BUILTIN_ROLE_TEMPLATES = ${JSON.stringify(roles)} as const;

export const BUILTIN_PERSONA_TEMPLATES = ${JSON.stringify(personas)} as const;

export const BUILTIN_WORKFLOW_TEMPLATES = ${JSON.stringify(workflows)} as const;
`;

fs.writeFileSync(outFile, body, 'utf8');
console.log('[embed-agent-catalog] wrote', outFile);
